import { readFileSync, writeFileSync } from "node:fs";

// portal-first-paint-v1
//
// The generated portal used to boot with an empty grade list and fetch the whole
// grade -> subject -> chapter -> lesson tree from the browser after hydration, so
// every visitor stared at a spinner for one full Sanity round trip. This installer
// lets the server hand the already published tree to the portal, keeps the live
// Sanity subscription untouched, and asks the Sanity image pipeline for correctly
// sized renditions instead of the full-resolution originals.

const portalPath = "app/SchoolLearningPortal.tsx";
const queryModulePath = "lib/sanity/portal-query.ts";

let portal = readFileSync(portalPath, "utf8");

function replaceRequired(label, search, replacement) {
  if (portal.includes(replacement)) return;
  if (!portal.includes(search)) throw new Error(`${label}: source pattern was not found`);
  portal = portal.replace(search, replacement);
}

function replaceAllRequired(label, search, replacement) {
  if (portal.includes(replacement)) return;
  if (!portal.includes(search)) throw new Error(`${label}: source pattern was not found`);
  portal = portal.replaceAll(search, replacement);
}

// 1. Mirror the portal query into a shared module so the server prefetch always
//    runs the exact query the browser would have run. The portal keeps the
//    literal in place — several audits assert the query markers live there — and
//    this module is regenerated from it on every build, so the two cannot drift.
const queryMatch = portal.match(/const portalQuery = `\n([\s\S]*?)\n`;\n/);
if (!queryMatch) throw new Error("portal query: source pattern was not found");

writeFileSync(
  queryModulePath,
  `// Generated by scripts/optimize-portal-first-paint.mjs. Do not edit by hand.
// Mirrors the portalQuery literal in app/SchoolLearningPortal.tsx so the server
// prefetch in lib/sanity/portal.ts stays byte-for-byte identical to the query
// the browser uses for its live refresh.

export const PORTAL_QUERY = \`
${queryMatch[1]}
\`;
`,
);

// 2. Ask Sanity for a rendition that matches the slot instead of shipping the
//    original upload, which is regularly several megabytes per lesson image.
replaceRequired(
  "sanity image sizing helper",
  "const portalQuery = `\n",
  `function sanityImageUrl(url: string | undefined, width: number): string | undefined {
  if (!url || !url.includes("cdn.sanity.io") || url.includes("?")) return url;
  return \`\${url}?w=\${width}&q=75&auto=format&fit=max\`;
}

const portalQuery = \`
`,
);

replaceRequired(
  "portable text image sizing",
  '<img src={url} alt={image.alt || "Foto e mësimit"} loading="lazy" />',
  '<img src={sanityImageUrl(url, 1200)} alt={image.alt || "Foto e mësimit"} loading="lazy" decoding="async" />',
);

replaceAllRequired(
  "flashcard image sizing",
  "<img src={card.image?.asset?.url} alt={card.image?.alt || card.front} />",
  '<img src={sanityImageUrl(card.image?.asset?.url, 900)} alt={card.image?.alt || card.front} loading="lazy" decoding="async" />',
);

replaceRequired(
  "lesson cover image sizing",
  `            <img
              className={styles.coverImage}
              src={imageUrl}
              alt={selectedLesson.coverImage?.alt || selectedLesson.title}
            />`,
  `            <img
              className={styles.coverImage}
              src={sanityImageUrl(imageUrl, 1200)}
              alt={selectedLesson.coverImage?.alt || selectedLesson.title}
              decoding="async"
            />`,
);

// 3. Accept the server-rendered tree and seed the portal state from it.
replaceRequired(
  "server rendered portal data",
  `export default function ClassicLearningPortal({
  isAdmin = false,
  isAuthenticated = false,
}: {
  isAdmin?: boolean;
  isAuthenticated?: boolean;
}) {
  const [grades, setGrades] = useState<Grade[]>([]);`,
  `export default function ClassicLearningPortal({
  isAdmin = false,
  isAuthenticated = false,
  initialGrades,
}: {
  isAdmin?: boolean;
  isAuthenticated?: boolean;
  initialGrades?: unknown;
}) {
  // The server hands over plain published JSON; narrow it once, here.
  const seededGrades = useMemo(
    () => (Array.isArray(initialGrades) && initialGrades.length ? initialGrades as Grade[] : null),
    [initialGrades],
  );
  const [grades, setGrades] = useState<Grade[]>(() => seededGrades || []);`,
);

replaceRequired(
  "seeded loading state",
  "  const [loading, setLoading] = useState(true);",
  "  const [loading, setLoading] = useState(() => !seededGrades);",
);

replaceRequired(
  "background first refresh",
  `  useEffect(() => {
    void fetchPortal();
  }, [fetchPortal]);`,
  `  useEffect(() => {
    // With server data on screen the first refresh runs without the blocking
    // loader, so a publish landing between the render and hydration still shows
    // up without ever hiding the portal behind a spinner.
    void fetchPortal(!seededGrades);
  }, [fetchPortal, seededGrades]);

  useEffect(() => {
    // Restore the last opened grade straight from the server payload instead of
    // waiting for the background refresh to come back.
    if (!seededGrades || selectedGradeRef.current) return;
    if (window.location.hash === "#klasat") {
      window.localStorage.removeItem(SELECTED_GRADE_KEY);
      return;
    }
    const savedId = window.localStorage.getItem(SELECTED_GRADE_KEY);
    const restored = savedId ? seededGrades.find((grade) => grade._id === savedId) || null : null;
    if (!restored) return;
    selectedGradeRef.current = restored;
    setSelectedGrade(restored);
  }, [seededGrades]);`,
);

if (!portal.includes("// portal-first-paint-v1")) {
  portal = portal.replace('"use client";', '"use client";\n\n// portal-first-paint-v1');
}

const markers = [
  "// portal-first-paint-v1",
  "function sanityImageUrl(",
  "initialGrades?: unknown;",
  "useState<Grade[]>(() => seededGrades || [])",
  "void fetchPortal(!seededGrades);",
];

for (const marker of markers) {
  if (!portal.includes(marker)) throw new Error(`Portal first paint marker missing: ${marker}`);
}

writeFileSync(portalPath, portal);
console.log("Portal renders server data on first paint and requests sized Sanity images.");
